/** Local Worker/R2 only; never uploads to production or contacts WhatsApp. */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { PhotonImage } from '@cf-wasm/photon';
import { imageSize } from '../worker/image-size.js';
const APP=process.argv[2]||'http://127.0.0.1:8810',STUB=process.argv[3]||'http://127.0.0.1:8899';
assert.equal(new URL(APP).hostname,'127.0.0.1');assert.equal(new URL(STUB).hostname,'127.0.0.1');
let checks=0;const check=(name,value)=>{assert.ok(value,name);checks++;console.log('PASS '+name);};
const control=path=>fetch(STUB+path);
const id='bbbbbbbb-1111-4111-8111-111111111111';
const productPath='/@nafin-boutique/p/'+id;
await control('/__noproduct/0');await control('/__plan/free');
const pixels=new Uint8Array(800*600*4).fill(255);
for(let y=0;y<600;y++)for(let x=0;x<800;x++){const p=(y*800+x)*4;pixels[p]=x<400?230:20;pixels[p+1]=40;pixels[p+2]=x<400?20:230;}
const source=new PhotonImage(pixels,800,600),png=source.get_bytes();source.free();
const fields=new FormData();fields.set('draft_id',id);
fields.set('card',new Blob([png],{type:'image/png'}),'card.webp');fields.set('full',new Blob([png],{type:'image/png'}),'full.webp');
const uploaded=await fetch(APP+'/app/upload',{method:'POST',headers:{cookie:'sb-access=TEST',origin:APP},body:fields});
assert.equal(uploaded.status,200);const keys=await uploaded.json();
await control('/__productimg/'+encodeURIComponent(keys.card));
const html=await(await fetch(APP+productPath)).text();
const og=html.match(/property="og:image" content="([^"]+)"/)?.[1];
check('metadata uses canonical, versioned JPEG URL',/^https:\/\/bazarnow\.xyz\/preview\/products\/.+\/[a-f0-9]{32}\.jpg$/.test(og));
check('metadata declares true JPEG type and dimensions',html.includes('property="og:image:type" content="image/jpeg"')&&html.includes('property="og:image:width" content="600"')&&html.includes('property="og:image:height" content="600"'));
const path=new URL(og).pathname;
const original=await(await fetch(APP+'/img/'+keys.full)).arrayBuffer();
const r=await fetch(APP+path,{headers:{'user-agent':'WhatsApp/2.24.7.81 A'}});
check('actual workerd WASM endpoint returns image/jpeg 200',r.status===200&&r.headers.get('content-type')==='image/jpeg');
const bytes=new Uint8Array(await r.arrayBuffer());
check('decoded result matches declared 600 square under 200 KiB',JSON.stringify(imageSize(bytes))==='{"width":600,"height":600}'&&bytes.length<=200*1024);
check('response length and nosniff are correct',Number(r.headers.get('content-length'))===bytes.length&&r.headers.get('x-content-type-options')==='nosniff');
const decoded=PhotonImage.new_from_byteslice(bytes),rendered=decoded.get_raw_pixels();decoded.free();
const a=(300*600+10)*4,b=(300*600+589)*4;
check('real photo retains both colored edges without cropping/stretching',rendered[a]>rendered[a+2]&&rendered[b+2]>rendered[b]);
const hash=buffer=>createHash('sha256').update(new Uint8Array(buffer)).digest('hex');
check('original uploaded full photo is unchanged',hash(original)===hash(await(await fetch(APP+'/img/'+keys.full)).arrayBuffer()));
const head=await fetch(APP+path,{method:'HEAD'});
check('HEAD returns the same representation without a body',head.status===200&&head.headers.get('content-length')===r.headers.get('content-length')&&(await head.arrayBuffer()).byteLength===0);
const conditional=await fetch(APP+path,{headers:{'if-none-match':r.headers.get('etag')}});
check('conditional GET returns 304',conditional.status===304);
check('POST is forbidden', (await fetch(APP+path,{method:'POST'})).status===405);
await control('/__noproduct/1');
check('ineligible/missing product blocks even warmed cache', (await fetch(APP+path)).status===404);
check('ineligible product blocks conditional requests', (await fetch(APP+path,{headers:{'if-none-match':r.headers.get('etag')}})).status===404);
await control('/__noproduct/0');await control('/__productimg/-');
check('old cover URL stops resolving after image selection changes',(await fetch(APP+path)).status===404);
console.log(`${checks} local preview Worker checks passed`);
